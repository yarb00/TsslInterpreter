using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Net.Http;
using System.Reflection;
using System.Runtime.InteropServices;
using System.Text.Json;

namespace TsslInterpreter;

internal enum CriticalError
{
	WrongArguments,
	FileReadError,
	EmptyFile,
	NotSupportedLanguageVersion,
	CodeError
}

internal static class Program
{
	public const string Name = "TsslInterpreter";
	private const string latestLanguageVersion = "0.4";
	private const string jsonUpdateInfoLocation = "https://tssl.yarb00.dev/update/data/client/release.tssl-update-data.json";

	private readonly static Dictionary<CriticalError, (string errorMessage, int exitCode)> errorDataByErrorType = new()
	{
		[CriticalError.WrongArguments] = ("You should pass exactly 1 argument: the path to the code file.", 2),
		[CriticalError.FileReadError] = ("An error occurred while reading the code file. (does it exist? is it accessible?)", 3),
		[CriticalError.EmptyFile] = ("The code file is empty.", 4),
		[CriticalError.NotSupportedLanguageVersion] = ("The TSSL version specified in this script is not supported by this version of interpreter.", 5),
		[CriticalError.CodeError] = ("Your code contains an error.", 6)
	};

	public readonly static Version? Version = Assembly.GetExecutingAssembly().GetName().Version;
	private readonly static string title = $"TsslInterpreter{(Version is not null ? $" v{Version.ToString(3)}" : string.Empty)}";

	private static string? codeErrorInfo = null;

	public static void Main(string[] args)
	{
		Console.Title = title;

		if (!Debugger.IsAttached) AppDomain.CurrentDomain.UnhandledException += static (sender, e) =>
		{
			static string Linkify(string text) => Uri.EscapeDataString(text);

			string
				issueTitle = $"Unhandled exception: \"{((Exception)e.ExceptionObject).GetType().Name}\"",
				issueBody = $"""
					***Auto-generated by {Name}.***

					## Environment
					**{Name} version**: `{Assembly.GetExecutingAssembly().GetName().Version?.ToString(3) ?? "[Not available or not present.]"}`
					**OS**: `{RuntimeInformation.OSDescription}`

					## Exception info
					**Exception type**: `{((Exception)e.ExceptionObject).GetType().FullName}`
					**Exception message**: `{((Exception)e.ExceptionObject).Message}`
					**Inner exception type**: `{((Exception)e.ExceptionObject).InnerException?.GetType().FullName ?? "[Not available or not present.]"}`
					**Inner exception message**: `{((Exception)e.ExceptionObject).InnerException?.Message ?? "[Not available or not present.]"}`

					### Stack trace (inner exception)
					{((Exception)e.ExceptionObject).InnerException?.StackTrace?.Replace("   ", "    ") ?? "[Not available or not present.]"}
					### Stack trace
					{((Exception)e.ExceptionObject).StackTrace?.Replace("   ", "    ") ?? "[Not available or not present.]"}
					""",
				issueCreateLink = $"https://github.com/yarb00/TsslInterpreter/issues/new?title={Linkify(issueTitle)}&body={Linkify(issueBody)}";

			Console.WriteLine($"""

				{new string('=', title.Length)}
				An unhandled exception occurred!
				It's a serious error that should not normally happen.
				Please report it by pasting the URL below, logging in or creating a GitHub account, and filling an issue.

				Report URL:
				{issueCreateLink}

				If you know what you're doing, here are advanced details:

				Exception message: {((Exception)e.ExceptionObject).Message}
				Inner exception message: {((Exception)e.ExceptionObject).InnerException?.Message ?? "[Not available or not present.]"}
				===== Stack trace (inner exception): =====
				{((Exception)e.ExceptionObject).InnerException?.StackTrace ?? "[Not available or not present.]"}
				===== Stack trace: =====
				{((Exception)e.ExceptionObject).StackTrace ?? "[Not available or not present.]"}
				""");
		};

		AppDomain.CurrentDomain.ProcessExit += (sender, e) => Exit(shouldKillProcess: false);
		Console.CancelKeyPress += (sender, e) => Exit(shouldKillProcess: false);

		if (args.Length == 0) RunCodePlayground();
		else if (args.Length != 1) Panic(CriticalError.WrongArguments);

		if (args[0] is "--version" or "--check-updates" && Version is null) Panic();
		else if (args[0] == "--version" && Version is not null) Console.WriteLine(Version.ToString(3));
		else if (args[0] == "--check-updates" && Version is not null) CheckUpdates();
		else RunCodeFromFile(args[0]);
	}

	private static void CheckUpdates()
	{
		Console.WriteLine(title);
		Console.WriteLine(new string('=', title.Length));
		Console.WriteLine("Fetching the latest version from the internet...");

		if (Version is null) Panic();

		using HttpClient httpClient = new();

		HttpResponseMessage response;
		try
		{
			response = httpClient.GetAsync(jsonUpdateInfoLocation).Result.EnsureSuccessStatusCode();
		}
		catch
		{
			Panic();
			return;
		}

		string responseContent = response.Content.ReadAsStringAsync().Result;
		JsonElement jsonRoot = JsonDocument.Parse(
			response.Content.ReadAsStream(),
			new JsonDocumentOptions
			{
				CommentHandling = JsonCommentHandling.Skip,
				AllowTrailingCommas = true
			}
		).RootElement;

		string?
			latestVersionRaw = jsonRoot.GetProperty("latest_branch_version").GetString(),
			latestVersionInfo = jsonRoot.GetProperty("latest_branch_version_info").GetString();

		if (latestVersionRaw is null || latestVersionInfo is null) Panic();

		Version latestVersion = Version.Parse(latestVersionRaw ?? string.Empty);
		Version latestVersionTrimmed = new(latestVersion.Major, latestVersion.Minor, latestVersion.Build, 0);
		Version installedVersionTrimmed = new(Version!.Major, Version.Minor, Version.Build, 0);

		if (latestVersionTrimmed > installedVersionTrimmed) Console.WriteLine("A newer version is available!" + Environment.NewLine);

		Console.WriteLine($"Currently installed version: v{Version!.ToString(3)}.");
		Console.WriteLine($"Latest version: v{latestVersion!.ToString(3)}.");

		if (latestVersionTrimmed > installedVersionTrimmed) Console.WriteLine($"""

			Download the update and view info about it here
			(copy and paste the link to your browser):
			{latestVersionInfo ?? "[Error: server didn't sent the link to the update info.]"}
			""");
	}

	private static void RunCodePlayground()
	{
		Console.WriteLine(title);
		Console.WriteLine(new string('=', title.Length));

		ScriptEnvironment environment = new();
		environment.RunInstruction($"!TooSimpleScriptingLanguage {latestLanguageVersion}");

		while (true)
		{
			Console.WriteLine();
			Console.Write(">>> ");
			string? input = Console.ReadLine();
			if (input is null) Exit();
			else environment.RunInstruction(input);
		}
	}

	private static void RunCodeFromFile(string filePath)
	{
		string[] codeLines;

		try
		{
			codeLines = File.ReadAllLines(filePath);
		}
		catch (FileNotFoundException)
		{
			if (!filePath.EndsWith(".toosimple")) RunCodeFromFile($"{filePath}.toosimple");
			else Panic(CriticalError.FileReadError);
			return;
		}
		catch
		{
			Panic(CriticalError.FileReadError);
			return;
		}

		if (codeLines.Length == 0) Panic(CriticalError.EmptyFile);

		ScriptEnvironment environment = new();
		foreach (string codeLine in codeLines) environment.RunInstruction(codeLine);

		Exit();
	}

	public static void Panic(CriticalError? errorType = null, string? message = null)
	{
		codeErrorInfo = message;
		if (errorType is null || !errorDataByErrorType.TryGetValue((CriticalError)errorType, out (string message, int exitCode) error))
			Exit("An unknown error occurred.", 1);
		else Exit(error.message, error.exitCode);
	}

	public static void Exit(string message = "", int exitCode = 0, bool shouldKillProcess = true)
	{
		if (exitCode != 0) Console.WriteLine($"""

			{new string('=', title.Length)}
			{Name} had to close. Here's the reason:
			"{message}"
			""");
		if (exitCode == errorDataByErrorType[CriticalError.CodeError].exitCode && codeErrorInfo is not null) Console.WriteLine($"""
			{new string('=', title.Length)}
			Additional info:
			{codeErrorInfo}
			""");
		if (shouldKillProcess) Environment.Exit(exitCode);
	}
}
